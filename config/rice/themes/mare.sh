# Maré — nascido do oceano visto de cima encontrando a areia.
#
# As cores NÃO foram inventadas: saíram de uma redução a 8 cores do
# recorte que virou o papel de parede (mare-01.jpg). Por isso a paleta
# encaixa na imagem em vez de apenas combinar de longe — é literalmente
# a mesma tinta.
#
# A tensão do tema é a mesma da foto: água fria ocupando quase tudo,
# areia quente entrando por um canto. Quem manda em área é o teal; o
# calor entra como acento, em marca pontual.
#
# Por que o ACENTO é a AREIA e não a turquesa:
# a turquesa já é o fundo — usá-la como acento seria destacar com a cor
# que está em toda parte, e nada destacaria. A areia é o que aparece uma
# vez só na foto, e é exatamente esse o papel de um acento. É o mesmo
# raciocínio do Samurai, onde o âmbar da lanterna marca contra o preto.
#
# O FUNDO puxa para o teal, e não para o preto neutro:
# aqui o afastamento do Samurai é deliberado. Naquele, o calor vinha das
# lanternas e um fundo quente sujaria a tela. Neste, o frio É o assunto —
# a foto inteira é água. Preto neutro deixaria a barra parecendo recorte
# de outro tema colado por cima do mar.
NAME="Maré"

BG=071c1d        # água funda, longe da luz
BG_ALT=16302f    # superfície: a água um palmo acima do fundo
FG=dfe8e6        # espuma
MUTED=7f9a9c     # água rasa vista contra o céu
DIM=2a4445       # traço apagado, ainda dentro do teal

ACCENT=cc8e62    # areia molhada — tirada direto da imagem
ACCENT2=4a9d99   # turquesa da arrebentação, segunda voz

OK=7fae8b        # verde de maresia
WARN=d9b98d      # areia seca, mais clara que o acento
ERR=c9695c       # coral, o único vermelho que cabe num tema de mar

# Cor das pastas do Papirus que acompanha este tema.
# Teal: é a família do fundo. O acento (areia) daria pasta cor de laranja
# clara, que sobre água escura vira farol — mesmo erro que o comentário do
# Samurai descreve ao recusar o paleorange.
PASTAS=teal

